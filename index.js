bot.on("business_message", async (ctx) => {
  const msg = ctx.businessMessage;
  
  // ВЫВОДИМ В ЛОГИ ДЛЯ ОТЛАДКИ
  console.log(`Пришло сообщение: "${msg.text}", Исходящее: ${msg.is_outgoing}`);

  // Если сообщение отправлено вами (is_outgoing === true) — выходим
  if (msg.is_outgoing === true) {
    console.log("Это исходящее сообщение, игнорирую.");
    return;
  }

  // Если мы здесь, значит бот считает сообщение входящим от клиента
  await ctx.reply("Приветствую! Сейчас я не в сети,когда зайду в сеть, я обязательно прочту.Если хотите передать что-то срочное то лучше позвоните мне..");
});
